/**
 * Khung video.
 *
 * `enablejsapi=1` bật kênh `postMessage` để tua và phát mà không nạp lại khung.
 * Trên máy không phải web thì chưa dựng được (cần `react-native-webview`, chưa
 * cài) — nói thẳng ra thay vì để một ô trống.
 */
function YoutubeFrame({ videoId, start }: { videoId: string; start: number }) {
  const { L } = useL();
  if (Platform.OS !== 'web') {
    return (
      <View className="items-center justify-center bg-paper-canvas p-8">
        <Icon name="play" size={26} color={paper.muted} />
        <Text className="mt-2 text-center font-sans text-body text-paper-muted">
          {L('Phần luyện theo video hiện chỉ chạy trên bản web.', 'Video practice only works on the web for now.')}
        </Text>
      </View>
    );
  }

  // The in-app browser can keep youtube-nocookie in an about:blank state.
  // Use the regular official embed host here; it still embeds the official
  // player and keeps the keyboard seek controls working through postMessage.
  const origin = Platform.OS === 'web' && typeof window !== 'undefined' ? window.location.origin : '';
  const src = `https://www.youtube.com/embed/${videoId}?enablejsapi=1&origin=${encodeURIComponent(origin)}&start=${Math.floor(start)}&rel=0&modestbranding=1`;

  return (
    <View className="relative overflow-hidden bg-black" style={{ aspectRatio: 16 / 9 }}>
      {/* Thumbnail stays underneath while the official player loads. */}
      <Image
        source={{ uri: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg` }}
        resizeMode="cover"
        style={{ position: 'absolute', inset: 0, width: '100%', height: '100%' }}
      />
      {/* The official player is the interactive layer, so playback stays inside localhost. */}
      {React.createElement('iframe', {
        id: 'yt-player',
        src,
        allow: 'accelerometer; autoplay; encrypted-media; picture-in-picture',
        allowFullScreen: true,
        style: { position: 'absolute', inset: 0, width: '100%', height: '100%', border: 'none', backgroundColor: '#050807' },
        title: L('Video luyện chép chính tả', 'Dictation practice video'),
      })}
    </View>
  );
}
