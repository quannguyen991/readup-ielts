/**
 * Chép chính tả theo video YouTube.
 *
 * Video phát bằng TRÌNH NHÚNG CHÍNH THỨC của YouTube, nên chủ kênh vẫn nhận
 * lượt xem và quảng cáo — app chỉ dựng phần luyện tập bên cạnh.
 *
 * LẤY PHỤ ĐỀ: thử tự động trước, hỏng thì mời dán. YouTube đã khoá đường lấy
 * phụ đề từ máy chủ (đo 04/09/2026: mọi client InnerTube trả 0 track, mọi định
 * dạng timedtext trả 0 byte), nên đường tự động không thể là đường duy nhất.
 * Dán lại cũng sạch hơn về bản quyền: nội dung do chính người xem lấy từ trang
 * họ đang mở bằng nút "Show transcript" có sẵn của YouTube.
 *
 * KHÔNG LƯU GÌ. Phụ đề sống trong một phiên luyện rồi thôi.
 */

/** Hai chế độ luyện trên cùng một video. */
const MODES = [
  { key: 'shadowing' as const, label: 'Shadowing', labelEn: 'Shadowing', icon: 'play' as const },
  { key: 'dictation' as const, label: 'Chép chính tả', labelEn: 'Dictation', icon: 'pencil' as const },
  { key: 'quiz' as const, label: 'Quiz', labelEn: 'Quiz', icon: 'clipboard' as const },
];

type Phase = 'pick' | 'practice';

export default function YoutubeDictationScreen() {
  /*
    `?v=<id>` là đường vào từ Thư viện video.

    Nếu video ấy đã từng được chuẩn bị phụ đề thì vào thẳng phần luyện, KHÔNG
    quay lại màn dán. Đây là điểm khiến thư viện dùng được thật: dán một lần cho
    mỗi video, những lần sau mở là làm ngay.
  */
  const { v } = useLocalSearchParams<{ v?: string }>();
  const savedVideos = useVideoTranscriptStore((s) => s.videos);
  const remember = useVideoTranscriptStore((s) => s.save);

  const fromLibrary = typeof v === 'string' && v ? savedVideos[v] : undefined;
  const initialVideoId = typeof v === 'string' ? parseVideoId(v) : null;

  const [phase, setPhase] = useState<Phase>(fromLibrary || initialVideoId ? 'practice' : 'pick');
  const [urlInput, setUrlInput] = useState(
    typeof v === 'string' && v ? `https://www.youtube.com/watch?v=${v}` : '',
  );
  const [videoId, setVideoId] = useState<string | null>(fromLibrary?.videoId ?? initialVideoId);
  const [sentences, setSentences] = useState<TranscriptSentence[]>(fromLibrary?.sentences ?? []);
  const [autoGenerated, setAutoGenerated] = useState(fromLibrary?.autoGenerated ?? false);

  const start = (id: string, list: TranscriptSentence[], auto: boolean) => {
    setVideoId(id);
    setSentences(list);
    setAutoGenerated(auto);
    setPhase('practice');
    // Nhớ lại ngay, không đợi làm xong: người học có thể đóng tab giữa chừng, và
    // phần đáng tiếc nhất để mất chính là công dán phụ đề.
    remember(id, list, auto);
  };

  /*
    Chọn video → luyện: vào bằng nhịp chuyển trang. KHÔNG làm hiệu ứng khi sang câu
    trong lúc luyện — khoá lại cả khung là dựng lại trình nhúng YouTube, tức là
    tải lại video mỗi câu.
  */
  if (phase === 'pick' || !videoId) {
    return (
      <PageTransition routeKey="pick">
        <PickView urlInput={urlInput} onChangeUrl={setUrlInput} onReady={start} />
      </PageTransition>
    );
  }

  return (
    <PageTransition routeKey={`practice-${videoId}`}>
    <PracticeView
      videoId={videoId}
      sentences={sentences}
      autoGenerated={autoGenerated}
      onReady={start}
      onExit={() => {
        setPhase('pick');
        setVideoId(null);
        setSentences([]);
      }}
    />
    </PageTransition>
  );
}

// ------------------------------------------------------------------ chọn video

function PickView({
  urlInput,
  onChangeUrl,
  onReady,
}: {
  urlInput: string;
  onChangeUrl: (v: string) => void;
  onReady: (videoId: string, sentences: TranscriptSentence[], auto: boolean) => void;
}) {
  const { L } = useL();
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [needPaste, setNeedPaste] = useState(false);
  const [pasted, setPasted] = useState('');

  const videoId = parseVideoId(urlInput);

  const tryAuto = async () => {
    if (!videoId) {
      setError(L('Đây không phải liên kết YouTube. Dán lại đường dẫn hoặc mã video.', "That isn't a YouTube link. Paste the link or video ID again."));
      return;
    }
    setLoading(true);
    setError(null);
    setNeedPaste(false);
    try {
      const res = await fetch(`/api/youtube/transcript?url=${encodeURIComponent(urlInput)}`);
      const data = (await res.json()) as {
        sentences?: TranscriptSentence[];
        autoGenerated?: boolean;
        error?: string;
      };
      if (!res.ok || !data.sentences?.length) {
        setError(data.error ?? L('Không lấy được phụ đề tự động.', "Couldn't fetch subtitles automatically."));
        setNeedPaste(true);
        return;
      }
      onReady(videoId, data.sentences, Boolean(data.autoGenerated));
    } catch {
      setError(L('Không gọi được máy chủ.', "Couldn't reach the server."));
      setNeedPaste(true);
    } finally {
      setLoading(false);
    }
  };

  const usePasted = () => {
    if (!videoId) return;
    const list = parsePastedTranscript(pasted);
    if (list.length === 0) {
      setError(L('Chưa đọc được câu nào từ phần vừa dán. Kiểm tra lại xem đã chép đủ chưa.', "Couldn't read any sentences from what you pasted. Check you copied all of it."));
      return;
    }
    onReady(videoId, list, false);
  };

  return (
    <TaskShell
      backHref="/sentence"
      backLabel={L('Quay lại Luyện câu', 'Back to Sentence practice')}
      variant="full"
      title={L('Chép chính tả theo video', 'Video dictation')}
      subtitle="YouTube dictation"
      icon="play"
      tone="paper"
      paperGrid={false}
    >
      {/*
        DẪN SANG KHO CÓ SẴN TRƯỚC, không dẫn thẳng vào ô dán liên kết.

        YouTube chặn máy chủ lấy phụ đề. Đo trực tiếp: đường lấy tự động chạy
        được khi máy chủ là máy cá nhân, còn từ máy chủ Vercel thì YouTube trả
        về "cần đăng nhập để xác nhận không phải bot" cho MỌI video. Nên trên
        bản đang chạy, mọi liên kết dán vào đây đều rơi xuống bước dán phụ đề
        bằng tay — mà đó là năm thao tác qua lại giữa hai tab.

        Kho VOA thì bấm một cái là làm được ngay. Để nó đứng trên là nói thật
        về việc đường nào đi được, chứ không phải giấu tính năng đi.
      */}
      <View className="mb-4 max-w-[760px] flex-row flex-wrap items-center gap-3 rounded-card border border-brand-soft bg-brand-tint p-4">
        <Icon name="sparkle" size={18} color={paper.brandMid} />
        <Text className="min-w-[240px] flex-1 font-sans text-body text-paper-body">
          {L('Muốn làm ngay thì dùng kho bài nghe có sẵn lời — bấm một cái là vào bài, không phải dán gì.', 'Want to start right away? Use the listening library with transcripts — one tap and you are in, nothing to paste.')}
        </Text>
        <Button
          variant="brand"
          label={L('Kho bài nghe', 'Listening library')}
          iconRight="arrow-right"
          onPress={() => router.push('/sentence/audio' as never)}
        />
      </View>

      <View className="max-w-[760px] rounded-card border border-brand-soft bg-white p-5">
        <Text className="font-sans text-bodyLg text-paper-body">
          {L('Dán liên kết một video YouTube có phụ đề tiếng Anh. Video phát ngay trong trang, bạn nghe từng câu rồi điền lại vào ô chữ bên cạnh.', 'Paste a link to a YouTube video with English subtitles. It plays right on the page — listen to each sentence and fill it into the letter boxes alongside.')}
        </Text>
        <Text className="mt-2 font-sans text-label text-paper-muted">
          {L('YouTube chặn máy chủ lấy phụ đề, nên phần lớn video sẽ cần bạn dán phụ đề vào — app hướng dẫn ngay bên dưới khi gặp.', "YouTube blocks servers from fetching subtitles, so most videos will need you to paste them in — the app shows you how below when that happens.")}
        </Text>

        <View className="mt-4 flex-row flex-wrap items-center gap-2">
          <View className="min-w-[260px] flex-1 flex-row items-center gap-2 rounded-card border border-brand-soft bg-white px-4">
            <Icon name="search" size={17} color={paper.muted} />
            <TextInput
              value={urlInput}
              onChangeText={(t) => {
                onChangeUrl(t);
                setError(null);
                setNeedPaste(false);
              }}
              placeholder="https://www.youtube.com/watch?v=…"
              placeholderTextColor={paper.muted}
              autoCapitalize="none"
              autoCorrect={false}
              className="h-11 flex-1 font-sans text-body text-paper-ink"
              style={{ outlineStyle: 'none' } as never}
            />
          </View>
          <Button
            variant="brand"
            label={loading ? L('Đang lấy phụ đề…', 'Fetching subtitles…') : L('Lấy phụ đề', 'Get subtitles')}
            iconRight="arrow-right"
            disabled={loading || !videoId}
            onPress={() => void tryAuto()}
          />
        </View>

        {videoId ? (
          <Text className="mt-2 font-sans text-label text-paper-muted">
            {L('Nhận ra video:', 'Video detected:')} <Text className="font-strong">{videoId}</Text>
          </Text>
        ) : null}

        {error ? (
          <View className="mt-3 flex-row items-start gap-2 rounded-panel border border-warning bg-warning-soft p-3">
            <Icon name="info" size={16} color={color.warning} strokeWidth={2} />
            <Text className="flex-1 font-sans text-body text-warning-ink">{error}</Text>
          </View>
        ) : null}

        {needPaste ? (
          <View className="mt-4 rounded-panel border border-brand-soft bg-brand-tint p-4">
            <Text className="font-strong text-body text-paper-ink">{L('Dán phụ đề vào đây', 'Paste the subtitles here')}</Text>
            {/*
              Hướng dẫn phải nói ĐÚNG các nút có thật trên YouTube — bảo người
              dùng "lấy transcript" mà không nói lấy ở đâu thì họ đứng lại ngay
              bước này.
            */}
            <Text className="mt-1 font-sans text-label text-paper-body">
              {L('Mở video trên YouTube → bấm', 'Open the video on YouTube → tap')} <Text className="font-strong">…more</Text> {L('dưới tiêu đề →', 'under the title →')}{' '}
              <Text className="font-strong">Show transcript</Text>
              {L(' → bôi đen toàn bộ rồi chép vào ô dưới. App tự bỏ mốc thời gian và cắt thành câu.', ' → select it all and paste it below. The app strips the timestamps and splits it into sentences.')}
            </Text>
            <TextInput
              value={pasted}
              onChangeText={setPasted}
              multiline
              placeholder={'0:00\nHello and welcome…'}
              placeholderTextColor={paper.muted}
              className="mt-3 min-h-[140px] rounded-panel border border-brand-soft bg-white p-3 font-sans text-body text-paper-ink"
            />
            <Button
              className="mt-3 self-start"
              variant="brand"
              label={L('Dùng phụ đề này', 'Use these subtitles')}
              iconRight="check"
              disabled={pasted.trim().length === 0}
              onPress={usePasted}
            />
          </View>
        ) : null}
      </View>
    </TaskShell>
  );
}

// ---------------------------------------------------------------- luyện tập

function PracticeView({
  videoId,
  sentences,
  autoGenerated,
  onReady,
  onExit,
}: {
  videoId: string;
  sentences: TranscriptSentence[];
  autoGenerated: boolean;
  onReady: (videoId: string, list: TranscriptSentence[], auto: boolean) => void;
  onExit: () => void;
}) {
  const { L } = useL();
  const [index, setIndex] = useState(0);
  const [typed, setTyped] = useState('');
  const [revealed, setRevealed] = useState(false);
  const [doneCount, setDoneCount] = useState(0);
  /*
    Hai chế độ trên CÙNG một video, không phải hai màn riêng.

    Chép chính tả rèn tai bắt được ÂM; nghe hiểu rèn việc nắm Ý. Đó là hai kỹ năng
    khác nhau và cái thứ hai không tự đến từ cái thứ nhất — chép đúng từng chữ mà
    không hiểu người ta nói gì thì vẫn không làm được đề Listening thật. Để chung
    một màn vì người học thường muốn làm cả hai trên đúng video vừa nghe, lúc còn
    nhớ nội dung.
  */
  const [mode, setMode] = useState<'shadowing' | 'dictation' | 'quiz'>('dictation');

  const inputRef = useRef<TextInput>(null);
  const logQuestions = useStudyStore((s) => s.logQuestions);

  const sentence = sentences[index] ?? { start: 0, end: 0, text: '' };
  const board = useMemo(() => buildLetterBoard(sentence.text), [sentence.text]);
  const grade = useMemo(() => gradeLetters(board.answer, typed), [board.answer, typed]);
  const solved = grade.done || revealed;
  // Ô chữ tự thu nhỏ để từ dài nhất vừa một dòng (điện thoại).
  const [gridWidth, setGridWidth] = useState(0);
  const cells = fitCells(gridWidth - 8, longestWordLetters(board));

  /*
    Game khi học (chế độ chép chính tả): chấm câu ĐÚNG MỘT LẦN, ngay lúc gõ đúng
    trọn câu. "Xem đáp án" là bỏ cuộc — trúng đòn. Bỏ qua câu thì không tính gì:
    phụ đề tự động của YouTube có câu nghe không ra, phạt câu đó là phạt oan.
  */
  // Bật game thì nhát chém đã có tiếng; pháo giấy im cho khỏi kêu đôi.
  const gameOn = useGameStore((s) => s.enabled);
  const strike = useSentenceStrike(`${videoId}:${index}`, 'listen');
  useEffect(() => {
    if (mode === 'dictation' && grade.done && !revealed) strike(true);
  }, [mode, grade.done, revealed, strike]);

  // Hỏi Cú: mở hộ từ đầu tiên chưa đúng.
  useOwlHint(
    mode === 'dictation' && !solved
      ? () => {
          const filled = revealNextWord(board, typed);
          if (filled === null) return false;
          setTyped(filled);
          inputRef.current?.focus();
          return true;
        }
      : null,
  );

  /**
   * Tua video về đúng đầu câu rồi phát.
   *
   * Dùng postMessage của IFrame API thay vì đổi `src`: đổi `src` sẽ nạp lại cả
   * trình phát, mất một hai giây và chớp đen — trong khi bài này bấm nghe lại
   * liên tục.
   */
  const play = useCallback(
    (from: number) => {
      if (Platform.OS !== 'web') return;
      const frame = document.getElementById('yt-player') as HTMLIFrameElement | null;
      frame?.contentWindow?.postMessage(
        JSON.stringify({ event: 'command', func: 'seekTo', args: [Math.max(0, from - 0.3), true] }),
        '*',
      );
      frame?.contentWindow?.postMessage(
        JSON.stringify({ event: 'command', func: 'playVideo', args: [] }),
        '*',
      );
    },
    [],
  );

  const replay = useCallback(() => play(sentence.start), [play, sentence.start]);

  const goNext = useCallback(() => {
    if (index + 1 < sentences.length) {
      setIndex(index + 1);
      setTyped('');
      setRevealed(false);
      setDoneCount((n) => n + 1);
      return;
    }
    logQuestions(sentences.length);
    setDoneCount(sentences.length);
  }, [index, sentences.length, logQuestions]);

  /*
    Phím tắt, đúng những phím ảnh tham chiếu dùng:

      Tab   — nghe lại câu này. Đặt ở Tab vì đó là phím ngón trỏ trái với tới
              mà không rời tay khỏi hàng phím chính, và nghe lại là thao tác
              lặp nhiều nhất trong bài.
      Enter — câu sau.

    Cả hai đều `preventDefault`: Tab mặc định nhảy tiêu điểm ra khỏi ô nhập,
    mà rời ô nhập thì mọi phím sau đó rơi vào hư không.
  */
  useEffect(() => {
    if (Platform.OS !== 'web') return;
    const onKey = (event: KeyboardEvent) => {
      if (event.key === 'Tab') {
        event.preventDefault();
        replay();
        inputRef.current?.focus();
      } else if (event.key === 'Enter' && solved) {
        event.preventDefault();
        goNext();
      }
    };
    // Pha BẮT (true), không phải pha nổi: ô nhập ẩn của react-native-web chặn
    // Enter lại, không cho nổi lên cửa sổ — xem ghi chú ở `LetterGrid`.
    window.addEventListener('keydown', onKey, true);
    return () => window.removeEventListener('keydown', onKey, true);
  }, [replay, goNext, solved]);

  // Sang câu mới thì tua tới đúng chỗ và trả tiêu điểm về ô nhập.
  useEffect(() => {
    const timer = setTimeout(() => inputRef.current?.focus(), 60);
    return () => clearTimeout(timer);
  }, [index]);

  const finished = doneCount >= sentences.length;

  if (sentences.length === 0) {
    return <PracticePrepView videoId={videoId} onReady={onReady} onExit={onExit} />;
  }

  return (
    <TaskShell
      backHref="/sentence"
      backLabel={L('Quay lại Luyện câu', 'Back to Sentence practice')}
      title={L('Chép chính tả theo video', 'Video dictation')}
      subtitle="YouTube dictation"
      icon="play"
      tone="paper"
      paperGrid={false}
      right={
        <View className="flex-row items-center gap-2">
          <View className="rounded-pill border border-brand-soft bg-white px-3.5 py-1.5">
            <Text className="font-strong text-label text-paper-body">
              {index + 1} / {sentences.length}
            </Text>
          </View>
          <Button variant="brandOutline" size="sm" label={L('Đổi video', 'Change video')} onPress={onExit} />
        </View>
      }
    >
      {autoGenerated ? (
        <View className="mb-4 flex-row items-start gap-2 rounded-panel border border-amber-200/30 bg-amber-100/10 p-3">
          <Icon name="info" size={16} color={color.warning} strokeWidth={2} />
          <Text className="flex-1 font-sans text-label text-white/75">
            {L('Phụ đề này do máy nghe rồi tự sinh, nên có thể sai chính tả hoặc thiếu dấu câu. Bài chấm tới từng chữ, nên chỗ nào bạn nghe đúng mà máy báo sai thì tin tai mình.', 'These subtitles were auto-generated, so they may have spelling mistakes or missing punctuation. Grading is letter by letter — if you heard it right and the app says otherwise, trust your ears.')}
          </Text>
        </View>
      ) : null}

      <View className="mb-4 flex-row flex-wrap gap-1.5">
        {MODES.map((m) => (
          <Pressable
            key={m.key}
            accessibilityRole="tab"
            aria-selected={mode === m.key}
            onPress={() => setMode(m.key)}
            className={[
              'flex-row items-center gap-2 rounded-pill border px-4 py-2',
              mode === m.key ? 'border-transparent bg-[#F7B955]' : 'border-white/20 bg-black/20',
            ].join(' ')}
          >
            <Icon
              name={m.icon}
              size={15}
              color={mode === m.key ? '#152238' : '#F3E4CB'}
              strokeWidth={2.1}
            />
            <Text
              className={['font-strong text-body', mode === m.key ? 'text-[#152238]' : 'text-white'].join(' ')}
            >
              {L(m.label, m.labelEn)}
            </Text>
          </Pressable>
        ))}
      </View>

      <CrossFade swapKey={mode}>
      {mode === 'quiz' ? (
        <ListeningQuiz videoId={videoId} sentences={sentences} onSeek={(at) => play(at)} />
      ) : mode === 'shadowing' ? (
        <ShadowingView sentence={sentence} onReplay={replay} onNext={goNext} />
      ) : (
      <View className="gap-4 rounded-panel bg-[#0B110D] p-3 lg:flex-row">
        {/* ------------------------------------------------------ trình phát */}
        <View className="lg:w-[42%]">
          <View className="overflow-hidden rounded-card border border-white/10 bg-black/35">
            <YoutubeFrame videoId={videoId} start={sentence.start} />
            <View className="flex-row flex-wrap items-center gap-2 border-t border-white/10 p-3">
              <Button variant="brand" size="sm" label={L('Nghe lại', 'Replay')} iconLeft="refresh" onPress={replay} />
              <Text className="font-sans text-label text-white/55">
                {L('hoặc bấm', 'or press')} <Text className="font-strong">Tab</Text>
              </Text>
            </View>
          </View>

          <View className="mt-4 overflow-hidden rounded-card border border-white/10 bg-black/25">
            <Text className="border-b border-white/10 px-4 py-2.5 font-strong uppercase tracking-wide text-white/50" style={{ fontSize: 10 }}>
              {L('Danh sách câu', 'Sentences')}
            </Text>
            <ScrollView style={{ maxHeight: 260 }}>
              {sentences.map((s, i) => (
                <Pressable
                  key={i}
                  accessibilityRole="button"
                  aria-selected={i === index}
                  onPress={() => {
                    setIndex(i);
                    setTyped('');
                    setRevealed(false);
                    play(s.start);
                  }}
                  className="flex-row items-center gap-2.5 border-b border-white/10 px-4 py-2.5"
                  style={{ backgroundColor: i === index ? 'rgba(247,185,85,0.14)' : 'transparent' }}
                >
                  <Text className="font-strong text-label text-paper-muted" style={{ width: 26 }}>
                    #{i + 1}
                  </Text>
                  <Text
                    className="min-w-0 flex-1 font-sans text-label"
                    numberOfLines={1}
                    style={{ color: i < index ? '#799084' : '#E7F1E8' }}
                  >
                    {i <= index || i < doneCount ? s.text : '•••••  •••••  •••'}
                  </Text>
                </Pressable>
              ))}
            </ScrollView>
          </View>
        </View>

        {/* -------------------------------------------------------- vùng gõ */}
        <View className="lg:flex-1">
          <View className="overflow-hidden rounded-card border border-white/10 bg-[#121A12] p-5">
            {grade.done && !revealed ? <Confetti seed={`yt-${videoId}-${index}`} silent={gameOn} /> : null}

            {/* Đường chạy cũ thành trận đấu: mặt đất là các câu của video, tia nạp đòn theo từ chép đúng. */}
            <BattleStrip
              step={{ index, total: sentences.length }}
              charge={{ value: solvedWordCount(board, grade), total: board.words.length, unit: L('từ', 'words') }}
            />

            <View className="mt-4 rounded-panel border-2 p-4" style={{ borderColor: paper.brandSoft }}>
              <View>
                <View
                  className="flex-row flex-wrap gap-y-2.5"
                  style={{ columnGap: cells.gap >= 4 ? 16 : 10 }}
                  onLayout={(e) => setGridWidth(Math.round(e.nativeEvent.layout.width))}
                >
                  {board.words.map((word, wordIndex) => (
                    <View key={wordIndex} className="flex-row items-center" style={{ gap: cells.gap }}>
                      {word.units.map((unit, unitIndex) =>
                        unit.kind === 'mark' ? (
                          <Text key={unitIndex} className="font-strong text-bodyLg text-paper-muted">
                            {unit.text}
                          </Text>
                        ) : (
                          <LetterCell
                            key={unitIndex}
                            char={
                              revealed
                                ? board.answer[unit.index] ?? ''
                                : typed[unit.index]?.toUpperCase() ?? ''
                            }
                            state={revealed ? 'correct' : grade.states[unit.index] ?? 'empty'}
                            caret={!revealed && typed.length === unit.index}
                            liveResult
                            size={cells.size}
                          />
                        ),
                      )}
                    </View>
                  ))}
                </View>

                <TextInput
                  ref={inputRef}
                  value={typed}
                  onChangeText={(t) => setTyped(sanitizeTyped(t, board.answer.length))}
                  accessibilityLabel={L('Vùng điền chữ cái', 'Letter input area')}
                  autoCapitalize="characters"
                  autoCorrect={false}
                  autoComplete="off"
                  spellCheck={false}
                  editable={!revealed}
                  style={{
                    position: 'absolute',
                    top: 0,
                    left: 0,
                    right: 0,
                    bottom: 0,
                    opacity: 0,
                    color: 'transparent',
                  }}
                />
              </View>

              <View className="mt-3 flex-row flex-wrap items-center justify-between gap-2">
                <Text className="font-sans uppercase tracking-wide text-paper-muted" style={{ fontSize: 9 }}>
                  {L('Mỗi ô là một chữ cái — Tab để nghe lại, Enter để sang câu', 'One letter per box — Tab to replay, Enter for the next sentence')}
                </Text>
                <Pressable
                  accessibilityRole="button"
                  onPress={() => setTyped('')}
                  className="flex-row items-center gap-1.5 py-1"
                >
                  <Icon name="refresh" size={13} color={paper.muted} strokeWidth={2} />
                  <Text className="font-semi uppercase tracking-wide text-paper-muted" style={{ fontSize: 9 }}>
                    {L('Xoá hết', 'Clear all')}
                  </Text>
                </Pressable>
              </View>
            </View>

            {solved ? (
              <View className="mt-4">
                <View className="flex-row items-center gap-2">
                  <Icon
                    name={revealed ? 'info' : 'check'}
                    size={18}
                    color={revealed ? color.warning : color.success}
                    strokeWidth={2.4}
                  />
                  <Text
                    className="font-strong text-bodyLg"
                    style={{ color: revealed ? color.warning : color.success }}
                  >
                    {revealed ? L('Đáp án của câu này', 'Answer for this sentence') : L('Bạn xuất sắc — đúng cả câu!', 'Excellent — the whole sentence is right!')}
                  </Text>
                </View>
                <View className="mt-2 rounded-panel bg-[#202D1B] p-3.5">
                  <Text className="font-strong text-bodyLg text-[#EFF7E9]">{sentence.text}</Text>
                </View>
              </View>
            ) : null}

            <View className="mt-4 flex-row flex-wrap items-center gap-2">
              {/*
                Nút xem đáp án chỉ hiện khi CHƯA giải xong. Bày sẵn cạnh ô nhập
                lúc mới vào câu là mời bỏ cuộc trước khi thử.
              */}
              {!solved ? (
                <Button
                  variant="brandOutline"
                  size="sm"
                  label={L('Xem đáp án', 'Show answer')}
                  iconLeft="info"
                  onPress={() => {
                    strike(false);
                    setRevealed(true);
                  }}
                />
              ) : null}
              <View className="flex-1" />
              {finished ? (
                <Badge label={L('Đã hết câu trong video', 'All sentences done')} tone="success" />
              ) : (
                <Button
                  variant={solved ? 'brand' : 'brandOutline'}
                  label={index + 1 < sentences.length ? L('Câu tiếp theo', 'Next sentence') : L('Xong', 'Done')}
                  iconRight="arrow-right"
                  onPress={goNext}
                />
              )}
            </View>
          </View>
        </View>
      </View>
      )}
      </CrossFade>
    </TaskShell>
  );
}

function PracticePrepView({
  videoId,
  onReady,
  onExit,
}: {
  videoId: string;
  onReady: (videoId: string, list: TranscriptSentence[], auto: boolean) => void;
  onExit: () => void;
}) {
  const { L } = useL();
  const [pasted, setPasted] = useState('');
  const [loading, setLoading] = useState(false);
  const [message, setMessage] = useState<string | null>(null);

  const loadTranscript = async () => {
    setLoading(true);
    setMessage(null);
    try {
      const res = await fetch(`/api/youtube/transcript?url=https://www.youtube.com/watch?v=${videoId}`);
      const data = (await res.json()) as { sentences?: TranscriptSentence[]; autoGenerated?: boolean; error?: string };
      if (!res.ok || !data.sentences?.length) {
        setMessage(data.error ?? L('Video chưa có phụ đề tự động. Bạn có thể dán transcript bên dưới.', 'This video has no auto subtitles. You can paste a transcript below.'));
        return;
      }
      onReady(videoId, data.sentences, Boolean(data.autoGenerated));
    } catch {
      setMessage(L('Không gọi được phụ đề lúc này. Bạn có thể dán transcript bên dưới.', "Couldn't fetch subtitles right now. You can paste a transcript below."));
    } finally {
      setLoading(false);
    }
  };

  const usePasted = () => {
    const list = parsePastedTranscript(pasted);
    if (!list.length) {
      setMessage(L('Chưa đọc được câu nào. Hãy dán transcript có mốc thời gian hoặc từng dòng câu.', "Couldn't read any sentences. Paste a transcript with timestamps, or one sentence per line."));
      return;
    }
    onReady(videoId, list, false);
  };

  return (
    <TaskShell backHref="/sentence/videos" backLabel={L('Quay lại thư viện video', 'Back to Video library')} title={L('Luyện nghe theo video', 'Video listening')} subtitle="Listening workspace" icon="play" tone="paper" paperGrid={false}>
      <View className="gap-4 rounded-panel bg-[#0B110D] p-3 lg:flex-row">
        <View className="lg:w-[46%]">
          <View className="overflow-hidden rounded-card border border-white/10 bg-black">
            <YoutubeFrame videoId={videoId} start={0} />
          </View>
          <View className="mt-3 rounded-card border border-white/10 bg-black/25 p-4">
            <Text className="font-strong uppercase tracking-[2px] text-[#9ED66C]" style={{ fontSize: 11 }}>{L('Video đã chọn', 'Selected video')}</Text>
            <Text className="mt-2 font-sans text-body text-white/65">{L('Nghe video ở bên trái, sau đó chọn chế độ luyện ở workspace.', 'Watch the video on the left, then pick a practice mode in the workspace.')}</Text>
            <Button className="mt-4 self-start" variant="brandOutline" label={L('Đổi video', 'Change video')} onPress={onExit} />
          </View>
        </View>

        <View className="flex-1 rounded-card border border-white/10 bg-[#121A12] p-5">
          <View className="flex-row items-center justify-between gap-3">
            <View>
              <Text className="font-heavy text-sectionTitle text-[#F4FAEA]">{L('Chuẩn bị workspace', 'Set up the workspace')}</Text>
              <Text className="mt-1 font-sans text-body text-white/55">{L('Một lần chuẩn bị transcript, những lần sau vào luyện ngay.', 'Prepare the transcript once, then jump straight into practice next time.')}</Text>
            </View>
            <View className="rounded-pill border border-[#F7B955]/45 bg-[#F7B955]/10 px-3 py-1.5">
              <Text className="font-strong text-label text-[#F7D28C]">{L('CÂU HỎI VIDEO', 'VIDEO QUESTIONS')}</Text>
            </View>
          </View>

          <View className="mt-5 rounded-panel border border-[#657447] bg-[#172313] p-5">
            <Text className="font-strong text-bodyLg text-[#EFF7E9]">{L('Chọn cách bắt đầu', 'Choose how to start')}</Text>
            <Text className="mt-2 font-sans text-body text-white/60">{L('Nếu video có phụ đề, hệ thống sẽ dựng ngay các câu để Shadowing, Dictation và Quiz.', 'If the video has subtitles, the app builds the sentences for Shadowing, Dictation and Quiz right away.')}</Text>
            <Button className="mt-4 self-start" variant="brand" label={loading ? L('Đang lấy phụ đề…', 'Fetching subtitles…') : L('Lấy phụ đề tự động', 'Get subtitles automatically')} iconRight="arrow-right" disabled={loading} onPress={() => void loadTranscript()} />
            {message ? <Text className="mt-3 font-sans text-label text-[#F7D28C]">{message}</Text> : null}
          </View>

          <Text className="mt-5 font-strong uppercase tracking-[2px] text-white/45" style={{ fontSize: 10 }}>{L('Hoặc dán transcript từ YouTube', 'Or paste a transcript from YouTube')}</Text>
          <TextInput value={pasted} onChangeText={setPasted} multiline placeholder={'0:00\nHello and welcome…'} placeholderTextColor="#71806D" className="mt-2 min-h-[150px] rounded-panel border border-white/10 bg-black/20 p-4 font-sans text-body text-[#EFF7E9]" />
          <Button className="mt-3 self-start" variant="brandOutline" label={L('Mở màn luyện', 'Start practising')} iconRight="check" disabled={!pasted.trim()} onPress={usePasted} />
        </View>
      </View>
    </TaskShell>
  );
}

