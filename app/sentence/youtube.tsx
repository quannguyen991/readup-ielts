/**
 * Màn phụ đề: toàn bộ câu của video, dòng đang phát được tô theo đúng thời gian của
 * trình phát. Chạm một dòng để tua tới đó. Bấm "Dịch" thì dịch cả video một lần rồi
 * lưu trên máy này — mở lại không tốn thêm lượt AI.
 */
function TranscriptView({
  videoId,
  sentences,
  onSeek,
}: {
  videoId: string;
  sentences: TranscriptSentence[];
  onSeek: (at: number) => void;
}) {
  const { L } = useL();
  const token = useAuthStore((s) => s.session?.access_token ?? null);
  const stored = useVideoTranscriptStore((s) => s.translations[videoId]);
  const setTranslations = useVideoTranscriptStore((s) => s.setTranslations);
  const [active, setActive] = useState(0);
  const [showVi, setShowVi] = useState(Boolean(stored && stored.length > 0));
  const [busy, setBusy] = useState<{ done: number; total: number } | null>(null);
  const [error, setError] = useState<string | null>(null);
  const rowY = useRef<number[]>([]);
  const scroller = useRef<ScrollView>(null);

  // Bản dịch đã lưu chỉ dùng khi khớp đúng số câu. Lệch số nghĩa là phụ đề đã đổi, phải dịch lại.
  const translations = stored && stored.length === sentences.length ? stored : null;

  const onTime = useCallback((seconds: number) => setActive(indexAt(sentences, seconds)), [sentences]);

  // Giữ dòng đang phát ở gần giữa khung cuộn.
  useEffect(() => {
    const y = rowY.current[active];
    if (y !== undefined) scroller.current?.scrollTo({ y: Math.max(0, y - 80), animated: true });
  }, [active]);

  const toggleVi = async () => {
    if (showVi) {
      setShowVi(false);
      return;
    }
    setError(null);
    setShowVi(true);
    if (translations) return;
    setBusy({ done: 0, total: sentences.length });
    const out = await translateAllLines(sentences.map((s) => s.text), token, (done, total) => setBusy({ done, total }));
    setBusy(null);
    if (out.ok) {
      setTranslations(videoId, out.lines);
    } else {
      setError(out.message);
      setShowVi(false);
    }
  };

  return (
    <View className="gap-4 rounded-panel bg-paper-canvas p-3 lg:flex-row">
      <View className="lg:w-[42%]">
        <View className="overflow-hidden rounded-card border border-brand-soft bg-white">
          <YoutubeFrame videoId={videoId} start={0} onTime={onTime} />
        </View>
      </View>

      <View className="min-w-0 flex-1 overflow-hidden rounded-card border border-brand-soft bg-white">
        <View className="flex-row flex-wrap items-center justify-between gap-3 border-b border-brand-soft px-4 py-2.5">
          <Text className="font-strong uppercase tracking-wide text-paper-muted" style={{ fontSize: 12 }}>
            {L('Phụ đề', 'Transcript')} · {sentences.length} {L('câu', 'lines')}
          </Text>
          <Pressable
            accessibilityRole="button"
            disabled={busy !== null}
            onPress={() => void toggleVi()}
            className="flex-row items-center gap-2 rounded-pill border px-3 py-1.5"
            style={{
              borderColor: showVi ? '#A8741A' : '#E4D6B5',
              backgroundColor: showVi ? 'rgba(247,185,85,0.16)' : 'transparent',
            }}
          >
            <Icon name="chat" size={14} color={showVi ? '#A8741A' : '#6E5626'} strokeWidth={2.1} />
            <Text className="font-strong text-label" style={{ color: showVi ? '#A8741A' : '#6E5626' }}>
              {busy
                ? L(`Đang dịch ${busy.done}/${busy.total}`, `Translating ${busy.done}/${busy.total}`)
                : showVi
                  ? L('Ẩn bản dịch', 'Hide translation')
                  : L('Dịch sang tiếng Việt', 'Translate to Vietnamese')}
            </Text>
          </Pressable>
        </View>

        {error ? <Text className="px-4 py-2 font-sans text-label text-[#B3261E]">{error}</Text> : null}

        <ScrollView ref={scroller} style={{ maxHeight: 460 }} contentContainerStyle={{ padding: 8, gap: 4 }}>
          {sentences.map((s, i) => {
            const on = i === active;
            return (
              <Pressable
                key={`${i}-${s.start}`}
                accessibilityRole="button"
                accessibilityLabel={`${clock(s.start)} ${s.text}`}
                accessibilityState={{ selected: on }}
                onLayout={(e) => {
                  rowY.current[i] = e.nativeEvent.layout.y;
                }}
                onPress={() => {
                  setActive(i);
                  onSeek(s.start);
                }}
                className="rounded-panel px-3 py-2.5"
                style={{ backgroundColor: on ? 'rgba(247,185,85,0.16)' : 'transparent' }}
              >
                <View className="flex-row items-start gap-3">
                  <Text
                    className="font-mid text-label"
                    style={{ color: on ? '#A8741A' : 'rgba(60,40,10,0.5)', minWidth: 42 }}
                  >
                    {clock(s.start)}
                  </Text>
                  <View className="min-w-0 flex-1 gap-1">
                    {/* Màu đặt bằng style: class arbitrary như text-[#…] không được NativeWind áp dụng ở đây. */}
                    <Text
                      className={on ? 'font-strong text-body' : 'font-sans text-body'}
                      style={{ color: on ? '#141A33' : '#3C3A44' }}
                    >
                      {s.text}
                    </Text>
                    {showVi && translations ? (
                      <Text className="font-sans text-label" style={{ color: '#2E7D4F', opacity: 0.9 }}>
                        {translations[i]}
                      </Text>
                    ) : null}
                  </View>
                </View>
              </Pressable>
            );
          })}
        </ScrollView>
      </View>
    </View>
  );
}

function ShadowingView({
  sentence,
  translation,
  onReplay,
  onNext,
}: {
  sentence: TranscriptSentence;
  translation?: string;
  onReplay: () => void;
  onNext: () => void;
}) {
  const { L } = useL();
  const listen = useListen();
  const [result, setResult] = useState<SayResult | null>(null);
  const [silent, setSilent] = useState(false);
  const armed = useRef(false);

  // Đổi câu thì bỏ kết quả của câu cũ — điểm của câu này không được dính sang câu khác.
  useEffect(() => {
    setResult(null);
    setSilent(false);
  }, [sentence.text]);

  // Micro vừa dừng hẳn: chấm đúng một lần cho lượt vừa nói.
  useEffect(() => {
    if (listen.listening || !armed.current) return;
    armed.current = false;
    if (!listen.text.trim()) {
      setResult(null);
      setSilent(true);
      return;
    }
    setSilent(false);
    setResult(scoreSaying(sentence.text, listen.text));
    // Chỉ chạy khi micro dừng hoặc có chữ mới; câu mẫu đã được effect trên bắt.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [listen.listening, listen.text]);

  const startRecording = () => {
    setResult(null);
    setSilent(false);
    armed.current = true;
    listen.start();
  };

  const pct = result ? percentOf(result) : null;
  return (
    <View className="gap-4 rounded-panel bg-paper-canvas p-5">
      <View className="flex-row items-center justify-between">
        <View>
          <Text className="font-strong uppercase tracking-[2px] text-[#2E7D4F]" style={{ fontSize: 12 }}>
            Shadowing mode
          </Text>
          <Text className="mt-1 font-sans text-body text-paper-muted">
            {L('Nghe một câu, bắt nhịp và nói lại theo giọng của video.', 'Listen to a sentence, catch the rhythm and say it back like the speaker.')}
          </Text>
        </View>
        <View className="rounded-pill border border-[#2E7D4F]/40 bg-[#2E7D4F]/10 px-3 py-1.5">
          <Text className="font-strong text-label text-[#2E7D4F]">{L('CÂU ĐANG HỌC', 'CURRENT SENTENCE')}</Text>
        </View>
      </View>

      <View className="min-h-[270px] items-center justify-center rounded-card border border-brand-soft bg-white px-8 py-10">
        <Text className="text-center font-heavy text-sectionTitle leading-tight text-paper-ink">
          {sentence.text}
        </Text>
        {translation ? (
          <Text className="mt-3 text-center font-sans text-bodyLg text-[#2E7D4F]" style={{ maxWidth: '85%' }}>
            {translation}
          </Text>
        ) : null}
        <Text className="mt-6 font-sans text-label text-paper-muted">
          {clock(sentence.start)} – {clock(sentence.end)} · {L('nghe, rồi nói lại', 'listen, then say it back')}
        </Text>
      </View>

      {/* Ghi âm rồi chấm từng từ: đúng xanh, thiếu gạch đỏ, nói thừa gạch vàng. Chấm theo chữ, không theo âm. */}
      {!listen.supported ? (
        <Text className="font-sans text-body text-[#A8741A]">{L('Ghi âm cần Chrome trên máy tính hoặc Android.', 'Recording needs Chrome on desktop or Android.')}</Text>
      ) : null}
      {silent ? (
        <Text className="font-sans text-body text-[#A8741A]">{L('Chưa nghe rõ. Thử lại gần micro hơn.', 'Could not hear you. Try again closer to the mic.')}</Text>
      ) : null}
      {result && pct !== null ? (
        <View className="gap-2 rounded-card border border-brand-soft bg-white p-4">
          <View className="flex-row items-baseline gap-3">
            <Text
              className="font-heavy text-sectionTitle"
              style={{ color: pct >= SAY_PASS * 100 ? '#2E7D4F' : pct >= 60 ? '#A8741A' : '#B3261E' }}
            >
              {pct}%
            </Text>
            <Text className="font-sans text-label text-paper-muted">
              {result.correct}/{result.total} {L('từ đúng', 'words right')}
            </Text>
          </View>
          <Text className="text-body leading-7">
            {result.tokens.map((t, i) => (
              <Text
                key={i}
                style={
                  t.status === 'correct'
                    ? { color: '#2E7D4F', fontWeight: '700' }
                    : t.status === 'missing'
                      ? { color: '#B3261E', textDecorationLine: 'underline' }
                      : { color: '#A8741A', textDecorationLine: 'line-through' }
                }
              >
                {t.word}
                {i < result.tokens.length - 1 ? ' ' : ''}
              </Text>
            ))}
          </Text>
        </View>
      ) : null}

      <View className="flex-row flex-wrap gap-3">
        <Button
          variant={listen.listening ? 'brand' : 'brandOutline'}
          label={listen.listening ? L('Dừng ghi', 'Stop') : result ? L('Nói lại', 'Try again') : L('Ghi âm', 'Record')}
          iconLeft="mic"
          disabled={!listen.supported}
          onPress={() => (listen.listening ? listen.stop() : startRecording())}
        />
        <Button variant="brandOutline" label={L('Nghe lại', 'Replay')} iconLeft="refresh" onPress={onReplay} />
        <Button variant="brand" label={L('Câu tiếp theo', 'Next sentence')} iconRight="arrow-right" onPress={onNext} />
      </View>
    </View>
  );
}

/**
 * Khung video.
 *
 * `enablejsapi=1` bật kênh `postMessage` để tua và phát mà không nạp lại khung.
 * Trên máy không phải web thì chưa dựng được (cần `react-native-webview`, chưa
 * cài) — nói thẳng ra thay vì để một ô trống.
 */
function YoutubeFrame({
  videoId,
  start,
  onTime,
}: {
  videoId: string;
  start: number;
  /** Nhận thời gian đang phát (giây) để đồng bộ dòng phụ đề. Chỉ có trên web. */
  onTime?: (seconds: number) => void;
}) {
  const { L } = useL();

  // YouTube chỉ gửi `infoDelivery` (có `currentTime`) sau khi trang được hỏi qua `listening`
  // (xem onLoad bên dưới). Chỉ nhận tin từ youtube.com; tin của trang khác bị bỏ qua.
  useEffect(() => {
    if (Platform.OS !== 'web' || !onTime) return;
    const onMessage = (event: MessageEvent) => {
      if (!String(event.origin).includes('youtube')) return;
      let data: unknown = event.data;
      if (typeof data === 'string') {
        try {
          data = JSON.parse(data);
        } catch {
          return;
        }
      }
      const msg = data as { event?: unknown; info?: { currentTime?: unknown } } | null;
      if (msg?.event === 'infoDelivery' && typeof msg.info?.currentTime === 'number') onTime(msg.info.currentTime);
    };
    window.addEventListener('message', onMessage);
    return () => window.removeEventListener('message', onMessage);
  }, [onTime]);

  if (Platform.OS !== 'web') {
    return (
      <View className="items-center justify-center bg-paper-canvas p-8">
        <Icon name="play" size={26} color={paper.muted} />
        <Text className="mt-2 text-center font-sans text-body text-paper-muted">
          {L('Phần luyện theo video hiện chỉ chạy trên bản web.', 'Video practice only works on the web for now.')}
        </Text>
      </View>
    );
  }

  // The in-app browser can keep youtube-nocookie in an about:blank state.
  // Use the regular official embed host here; it still embeds the official
  // player and keeps the keyboard seek controls working through postMessage.
  const origin = Platform.OS === 'web' && typeof window !== 'undefined' ? window.location.origin : '';
  const src = `https://www.youtube.com/embed/${videoId}?enablejsapi=1&origin=${encodeURIComponent(origin)}&start=${Math.floor(start)}&rel=0&modestbranding=1`;

  return (
    <View className="relative overflow-hidden bg-paper-canvas" style={{ aspectRatio: 16 / 9 }}>
      {/* Thumbnail stays underneath while the official player loads. */}
      <Image
        source={{ uri: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg` }}
        resizeMode="cover"
        style={{ position: 'absolute', inset: 0, width: '100%', height: '100%' }}
      />
      {/* The official player is the interactive layer, so playback stays inside localhost. */}
      {React.createElement('iframe', {
        id: 'yt-player',
        src,
        onLoad: () => {
          // Hỏi trình phát báo thời gian hiện tại. Không hỏi thì không có `infoDelivery`.
          const frame = document.getElementById('yt-player') as HTMLIFrameElement | null;
          frame?.contentWindow?.postMessage(JSON.stringify({ event: 'listening', id: 'yt-player', channel: 'widget' }), '*');
        },
        allow: 'accelerometer; autoplay; encrypted-media; picture-in-picture',
        allowFullScreen: true,
        style: { position: 'absolute', inset: 0, width: '100%', height: '100%', border: 'none', backgroundColor: '#F3EEE2' },
        title: L('Video luyện chép chính tả', 'Dictation practice video'),
      })}
    </View>
  );
}
