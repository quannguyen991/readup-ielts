import { fetchCaptionTracks } from '@/services/youtube/innertube';
import {
  groupIntoSentences,
  speechCues,
  parseTranscriptXml,
  parseVideoId,
  pickEnglishTrack,
  usableSentences,
} from '@/services/youtube/transcript';

/**
 * GET /api/youtube/transcript?url=...
 *
 * Trả về phụ đề tiếng Anh của video, đã gộp thành câu trọn vẹn có mốc thời
 * gian, để làm bài chép chính tả bên cạnh trình phát.
 *
 * CHẠY Ở MÁY CHỦ, không phải ở trình duyệt — YouTube không đặt CORS cho trang
 * xem nên trình duyệt không tự lấy được. Đây cũng là chỗ duy nhất chạm tới
 * YouTube, nên mọi ràng buộc nằm gọn một file.
 *
 * KHÔNG LƯU LẠI GÌ. Phụ đề trả thẳng về máy người dùng cho một phiên luyện rồi
 * thôi: nó là nội dung của chủ kênh, app chỉ mượn trong lúc người học đang xem
 * chính video đó bằng trình nhúng chính thức. Kho bài của app vẫn là 50 bộ đề
 * do dự án tự viết — xem `src/data/dictation-sets.ts`.
 */
export async function GET(request: Request): Promise<Response> {
  const url = new URL(request.url);
  const input = url.searchParams.get('url')?.trim() ?? '';

  const videoId = parseVideoId(input);
  if (!videoId) {
    return Response.json(
      { error: 'Liên kết không phải video YouTube. Dán lại đường dẫn hoặc mã video.' },
      { status: 400 },
    );
  }

  try {
    /*
      Hỏi InnerTube, KHÔNG cào trang watch nữa — xem `services/youtube/innertube.ts`
      để biết vì sao. Tóm tắt: cách cũ vẫn TÌM THẤY bảng phụ đề nhưng mọi
      `baseUrl` trong đó trả về 200 kèm 0 byte, nên người dùng nhận đúng một câu
      "video này không có phụ đề" cho mọi video, kể cả video có phụ đề thật.
    */
    const found = await fetchCaptionTracks(videoId);

    if (!found.ok) {
      /* Ba nguyên nhân, ba câu khác nhau — người đọc phải biết nên làm gì tiếp. */
      const message =
        found.reason === 'no_captions'
          ? 'Video này không có phụ đề nên chưa làm bài chép chính tả được.'
          : found.reason === 'blocked'
            ? 'YouTube không cho lấy phụ đề của video này (video riêng tư, giới hạn tuổi, hoặc chặn nhúng).'
            : 'Không nối được tới YouTube lúc này. Thử lại sau một lát.';
      return Response.json({ error: message }, { status: found.reason === 'unreachable' ? 502 : 404 });
    }

    const track = pickEnglishTrack(found.tracks);

    if (!track) {
      return Response.json(
        { error: 'Video này có phụ đề nhưng không có bản tiếng Anh.' },
        { status: 404 },
      );
    }

    const xml = await fetch(track.baseUrl, {
      headers: { 'Accept-Language': 'en-US,en;q=0.9' },
    });
    if (!xml.ok) {
      return Response.json({ error: 'Không tải được phụ đề của video này.' }, { status: 502 });
    }

    const sentences = usableSentences(
      groupIntoSentences(speechCues(parseTranscriptXml(await xml.text()))),
    );

    if (sentences.length === 0) {
      return Response.json(
        { error: 'Phụ đề của video này quá rời rạc để cắt thành câu.' },
        { status: 422 },
      );
    }

    return Response.json({
      videoId,
      // `asr` = phụ đề do máy nghe rồi sinh ra. Màn hình phải nói rõ điều đó:
      // bản máy hay sai chính tả, mà bài này chấm tới từng chữ cái.
      autoGenerated: track.kind === 'asr',
      sentences,
    });
  } catch {
    return Response.json({ error: 'Không lấy được phụ đề. Thử lại sau ít phút.' }, { status: 502 });
  }
}
