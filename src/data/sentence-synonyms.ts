export const SYN_ENTRIES: readonly SynEntry[] = RAW.map(([word, alts, vi, pos]) => ({ word, alts: alts.split('|'), vi, pos }));

const BY_WORD = new Map<string, SynEntry>();
for (const e of SYN_ENTRIES) if (!BY_WORD.has(e.word)) BY_WORD.set(e.word, e);

export function synonymEntry(word: string): SynEntry | undefined {
  return BY_WORD.get(word.toLowerCase());
}

