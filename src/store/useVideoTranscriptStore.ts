import { create } from 'zustand';
import { persist } from 'zustand/middleware';

import { STORAGE_PREFIX, storage } from './persist';
import type { TranscriptSentence } from '@/services/youtube/transcript';
import seedBilingual from '@/data/seed/bilingual-videos.json';

/**
 * Phụ đề người học đã chuẩn bị cho từng video, nhớ lại trên máy họ.
 *
 * VÌ SAO CẦN. App không tự lấy được phụ đề từ YouTube (xem `video-library.ts`),
 * nên mỗi video phải dán một lần. Không nhớ lại thì lần thứ hai mở đúng video ấy
 * người học lại phải mở YouTube, bấm Show transcript, bôi đen, chép — cho một
 * video họ đã chuẩn bị xong hôm qua. Đó là chỗ tính năng chết, không phải chỗ
 * dán lần đầu.
 *
 * CHỈ LƯU TRÊN MÁY NGƯỜI DÙNG, không đồng bộ lên máy chủ và không chia sẻ giữa
 * các tài khoản. Phụ đề là nội dung của chủ kênh; người học tự lấy về cho việc
 * học của mình là một chuyện, còn app gom lại thành kho dùng chung lại là chuyện
 * khác hẳn.
 */

export type PreparedVideo = {
  videoId: string;
  sentences: TranscriptSentence[];
  /** Máy tự sinh phụ đề hay người soạn — quyết định có hiện cảnh báo sai chính tả không. */
  autoGenerated: boolean;
  preparedAt: string;
  /** Câu đã chép đúng, để mở lại là đi tiếp chứ không phải bắt đầu lại. */
  doneCount: number;
};

type State = {
  videos: Record<string, PreparedVideo>;
  /**
   * Bản dịch tiếng Việt của từng câu, theo video, lưu trên máy này. Dịch một lần rồi
   * giữ: mở lại video không tốn thêm lượt AI. Mảng cùng thứ tự với `sentences`.
   */
  translations: Record<string, string[]>;
  save: (videoId: string, sentences: TranscriptSentence[], autoGenerated: boolean) => void;
  setProgress: (videoId: string, doneCount: number) => void;
  setTranslations: (videoId: string, lines: string[]) => void;
  forget: (videoId: string) => void;
};

const SEED_VIDEOS = (seedBilingual.prepared ?? {}) as Record<string, PreparedVideo>;
const SEED_TRANSLATIONS = (seedBilingual.translations ?? {}) as Record<string, string[]>;

export const useVideoTranscriptStore = create<State>()(
  persist(
    (set) => ({
      videos: SEED_VIDEOS,
      translations: SEED_TRANSLATIONS,

      setTranslations: (videoId, lines) =>
        set((s) => ({ translations: { ...s.translations, [videoId]: lines } })),

      save: (videoId, sentences, autoGenerated) =>
        set((s) => ({
          videos: {
            ...s.videos,
            [videoId]: {
              videoId,
              sentences,
              autoGenerated,
              preparedAt: new Date().toISOString(),
              // Dán lại phụ đề cho một video đã làm dở thì GIỮ tiến độ cũ: người
              // ta dán lại thường vì bản trước thiếu câu, không phải để làm lại
              // từ đầu.
              doneCount: s.videos[videoId]?.doneCount ?? 0,
            },
          },
        })),

      setProgress: (videoId, doneCount) =>
        set((s) => {
          const cur = s.videos[videoId];
          if (!cur) return s;
          // Chỉ tiến, không lùi: mở lại câu số 3 để nghe kỹ không được xoá việc
          // đã chép xong 10 câu.
          if (doneCount <= cur.doneCount) return s;
          return { videos: { ...s.videos, [videoId]: { ...cur, doneCount } } };
        }),

      forget: (videoId) =>
        set((s) => {
          const next = { ...s.videos };
          delete next[videoId];
          const nextTranslations = { ...s.translations };
          delete nextTranslations[videoId];
          return { videos: next, translations: nextTranslations };
        }),
    }),
    {
      name: `${STORAGE_PREFIX}video-transcripts`,
      storage: storage<State>(),
      merge: (persistedState, currentState) => {
        const p = (persistedState as Partial<State>) ?? {};
        const pVideos = p.videos ?? {};
        const pTranslations = p.translations ?? {};

        const mergedVideos = { ...SEED_VIDEOS, ...pVideos };
        for (const [id, seedVid] of Object.entries(SEED_VIDEOS)) {
          if (!mergedVideos[id] || !mergedVideos[id].sentences || mergedVideos[id].sentences.length === 0) {
            mergedVideos[id] = seedVid;
          }
        }

        const mergedTranslations = { ...SEED_TRANSLATIONS, ...pTranslations };
        for (const [id, seedTrans] of Object.entries(SEED_TRANSLATIONS)) {
          if (!mergedTranslations[id] || mergedTranslations[id].length === 0) {
            mergedTranslations[id] = seedTrans;
          }
        }

        return {
          ...currentState,
          ...p,
          videos: mergedVideos,
          translations: mergedTranslations,
        };
      },
    },
  ),
);

/** Video đã chuẩn bị, mới nhất lên đầu — dùng cho mục "Đang luyện dở". */
export function preparedList(videos: Record<string, PreparedVideo>): PreparedVideo[] {
  return Object.values(videos).sort((a, b) => b.preparedAt.localeCompare(a.preparedAt));
}
